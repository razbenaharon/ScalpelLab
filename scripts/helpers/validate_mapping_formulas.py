def parse_idx_timestamps(idx_path: Path) -> np.ndarray | None:
    """Return per-frame Unix timestamps (float64) from a .seq.idx file."""
    if not idx_path.exists():
        return None
    try:
        raw = idx_path.read_bytes()
    except OSError:
        return None
    n_records = len(raw) // _IDX_RECORD_SIZE
    if n_records == 0:
        return None
    u32 = np.frombuffer(raw[: n_records * _IDX_RECORD_SIZE], dtype="<u4")
    ts_sec = u32[_IDX_U32_TS_SEC :: _IDX_UINT32_PER_RECORD][:n_records].astype(np.float64)
    ts_sub = u32[_IDX_U32_TS_SUB :: _IDX_UINT32_PER_RECORD][:n_records]
    ms = (ts_sub & 0xFFFF).astype(np.float64)
    us = ((ts_sub >> 16) & 0xFFFF).astype(np.float64)
    return ts_sec + ms / 1_000.0 + us / 1_000_000.0


