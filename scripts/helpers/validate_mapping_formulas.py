def _ffprobe_basic(mp4: Path, ffprobe: str) -> tuple[int, float] | None:
    """Return (nb_frames, fps) for ``mp4`` or None on failure."""
    cmd = [
        ffprobe, "-v", "error", "-select_streams", "v:0",
        "-show_entries", "stream=nb_frames,avg_frame_rate,duration",
        "-of", "json", str(mp4),
    ]
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=30)
    except (subprocess.TimeoutExpired, OSError):
        return None
    if proc.returncode != 0:
        return None
    data = json.loads(proc.stdout or "{}")
    s = (data.get("streams") or [{}])[0]
    afr = s.get("avg_frame_rate", "0/1")
    if "/" in afr:
        num, den = afr.split("/", 1)
        fps = float(num) / float(den) if float(den) else 0.0
    else:
        fps = float(afr) if afr else 0.0
    try:
        nb = int(s.get("nb_frames") or 0)
    except (TypeError, ValueError):
        nb = 0
    if nb == 0:
        try:
            dur = float(s.get("duration") or 0.0)
            nb = int(round(dur * fps)) if fps else 0
        except ValueError:
            nb = 0
    return nb, fps


def _build_seq_idx_path(seq_root: Path, rec_date: str, case_no: int, camera: str) -> Path | None:
    """Find the .seq.idx for a (date, case, camera) tuple under SEQ_ROOT."""
    yy = rec_date[2:4]
    mm = rec_date[5:7]
    dd = rec_date[8:10]
    base = seq_root / f"DATA_{yy}-{mm}-{dd}" / f"Case{case_no}"
    cam_dir = base / camera
    if not cam_dir.is_dir():
        for child in base.iterdir() if base.is_dir() else []:
            if child.is_dir() and child.name.rstrip("_JUNKjunk") == camera:
                cam_dir = child
                break
        else:
            return None
    seqs = list(cam_dir.glob("*.seq"))
    if not seqs:
        return None
    idx = Path(str(seqs[0]) + ".idx")
    return idx if idx.exists() else None


