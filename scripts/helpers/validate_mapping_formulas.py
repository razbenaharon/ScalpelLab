def _parse_cases_arg(spec: str) -> list[tuple[str, int]]:
    """Parse a `YYYY-MM-DD:N,YYYY-MM-DD:M,...` --cases value into pairs."""
    out: list[tuple[str, int]] = []
    for tok in spec.split(","):
        tok = tok.strip()
        if not tok:
            continue
        if ":" not in tok:
            raise argparse.ArgumentTypeError(f"Bad case spec '{tok}': expected DATE:N.")
        date, case_str = tok.split(":", 1)
        try:
            out.append((date.strip(), int(case_str)))
        except ValueError as exc:
            raise argparse.ArgumentTypeError(f"Bad case spec '{tok}': {exc}") from exc
    return out


def _parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    ap = argparse.ArgumentParser(
        description=("Validate the composed OLD MP4 -> SEQ -> NEW MP4 frame "
                     "mapping with tight dHash checks."),
    )
    ap.add_argument("--old-root", default=DEFAULT_OLD_ROOT)
    ap.add_argument("--new-root", default=get_mp4_root())
    ap.add_argument("--seq-root", default=get_seq_root())
    ap.add_argument("--db", default=get_db_path())
    grp = ap.add_mutually_exclusive_group(required=True)
    grp.add_argument("--cases", type=_parse_cases_arg, default=None,
                     help="Comma-sep DATE:N pairs, e.g. 2025-10-12:1,2025-09-09:1")
    grp.add_argument("--date", default=None, help="YYYY-MM-DD (single-case mode)")
    ap.add_argument("--case", type=int, default=None,
                    help="Single-case mode: case number (paired with --date).")
    ap.add_argument("--cameras", nargs="*", default=None,
                    help="Restrict to these camera folder names.")
    ap.add_argument("--samples", type=int, default=15,
                    help="Anchor frames per camera (default: 15, spread evenly).")
    ap.add_argument("--local-radius", type=int, default=5,
                    help="Tight verify window radius on NEW MP4 in frames (default: 5).")
    ap.add_argument("--search-radius-seq", type=int, default=_DEFAULT_SEARCH_RADIUS_SEQ,
                    help=("K-space empirical search radius around i_old in SEQ "
                          f"frames (default: {_DEFAULT_SEARCH_RADIUS_SEQ})."))
    ap.add_argument("--hamming-threshold", type=int, default=16,
                    help="PASS if min_hamming_local <= this (default: 16 / 256).")
    ap.add_argument("--out-detailed-csv", default=None,
                    help="Per-anchor per-hypothesis CSV (one row each).")
