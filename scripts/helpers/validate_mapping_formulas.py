def summarise(camera_results: list[dict]) -> dict[str, dict]:
    """Per-hypothesis aggregate metrics across all anchors of one camera."""
    # Discover hypothesis names from the data (includes any runtime-added entries).
    names: list[str] = []
    seen: set[str] = set()
    for anc in camera_results:
        pf = anc.get("per_formula") or {}
        for k in pf:
            if k not in seen:
                seen.add(k)
                names.append(k)
    by_formula: dict[str, list[dict]] = {name: [] for name in names}
    for anc in camera_results:
        pf = anc.get("per_formula") or {}
        for name, info in pf.items():
            if info.get("out_of_range"):
                continue
            if info.get("min_hamming_local") is None:
                continue
            by_formula[name].append(info)

    summary: dict[str, dict] = {}
    for name in by_formula:
        infos = by_formula[name]
        if not infos:
            summary[name] = {"n": 0}
            continue
        min_hams = np.array([i["min_hamming_local"] for i in infos], dtype=np.float64)
        ham_at = np.array([i["hamming_at_predicted"] for i in infos], dtype=np.float64)
        best_offs = np.array([i["best_offset"] for i in infos], dtype=np.int64)
        residuals = np.array(
            [i["residual_K"] for i in infos if i.get("residual_K") is not None],
            dtype=np.int64,
        )
        n_good = int(np.sum(min_hams <= _GOOD_THRESHOLD_BITS))
        n_centred = int(np.sum(np.abs(best_offs) <= _BEST_OFFSET_TOLERANCE))
        n_resid_ok = int(np.sum(np.abs(residuals) <= _RESIDUAL_K_TOLERANCE)) if residuals.size else 0
        summary[name] = {
            "n": len(infos),
            "n_good": n_good,
            "n_centred": n_centred,
            "n_resid_ok": n_resid_ok,
            "mean_min_hamming": float(np.mean(min_hams)),
            "median_min_hamming": float(np.median(min_hams)),
            "mean_ham_at_predicted": float(np.mean(ham_at)),
            "median_best_offset": int(np.median(best_offs)),
            "max_abs_best_offset": int(np.max(np.abs(best_offs))),
            "median_residual_K": int(np.median(residuals)) if residuals.size else 0,
            "max_abs_residual_K": int(np.max(np.abs(residuals))) if residuals.size else -1,
        }
    return summary


def empirical_health(camera_results: list[dict]) -> dict:
    """How clean is the dHash-derived ground truth across this camera's anchors?

    Used both for the per-camera CLExport flag and for trusting g_linear.
    """
    hams = [r["hamming_empirical"] for r in camera_results
            if r.get("hamming_empirical") is not None]
    if not hams:
        return {"n": 0}
    arr = np.array(hams, dtype=np.float64)
    return {
        "n": len(hams),
        "mean": float(np.mean(arr)),
        "median": float(np.median(arr)),
        "max": float(np.max(arr)),
    }


def _verdict(s: dict, n_anchors: int) -> str:
    """Decide a short label for how well a hypothesis fits this camera.

    Surgical scenes are near-static, so the empirical-K column is noise
    dominated. The verdict is therefore driven by j-space metrics (does
    j_pred land near the local Hamming minimum on the NEW MP4?). The
    residual_K column is reported but not used to gate CONFIRMED.
    """
    if not s or s.get("n", 0) == 0:
        return "NO_DATA"
    n = s["n"]
    if n_anchors == 0:
        return "NO_DATA"
    good_frac = s["n_good"] / n
    centred_frac = s["n_centred"] / n
    if (good_frac >= 0.8 and centred_frac >= 0.8
            and s["mean_min_hamming"] <= 12):
        return "CONFIRMED"
    if good_frac >= 0.5 and s["mean_min_hamming"] <= 20:
        return "PLAUSIBLE"
    return "FAILS"


def _formula_order(summary: dict[str, dict]) -> list[str]:
    """Return hypothesis names in display order: G_HYPOTHESES first, then extras."""
    base = [name for name, _ in G_HYPOTHESES]
    extras = [k for k in summary.keys() if k not in base]
    return base + extras


