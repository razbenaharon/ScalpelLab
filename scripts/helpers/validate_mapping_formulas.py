# ---------------------------------------------------------------------------
# Core mapping f: SEQ frame -> NEW MP4 frame
# ---------------------------------------------------------------------------
def _f_seq_to_new(K: int, ctx: CameraContext) -> int:
    """Apply the NEW exporter's documented mapping for SEQ frame K -> NEW j.

    j = pre_roll + round((t_seq[K] - t_seq[0]) * 30)

    K is clamped to the valid IDX range; the caller is responsible for
    deciding whether out-of-range j values should be filtered.
    """
    if ctx.idx_frames <= 0:
        return -1
    Kc = max(0, min(int(K), ctx.idx_frames - 1))
    return ctx.pre_roll + int(round((ctx.t_seq[Kc] - ctx.t_cam) * TARGET_FPS))


# ---------------------------------------------------------------------------
# g hypotheses: OLD MP4 frame -> SEQ frame index
# ---------------------------------------------------------------------------
def _g_identity(i: int, ctx: CameraContext) -> int:
    return i


def _g_fps_scale_30(i: int, ctx: CameraContext) -> int:
    return int(round(i * ctx.source_fps / TARGET_FPS))


def _g_fps_scale_oldfps(i: int, ctx: CameraContext) -> int:
    if ctx.old_fps <= 0:
        return i
    return int(round(i * ctx.source_fps / ctx.old_fps))


def _g_shift_plus1(i: int, ctx: CameraContext) -> int:
    return i + 1


def _g_shift_minus1(i: int, ctx: CameraContext) -> int:
    return i - 1


def _g_pre_roll(i: int, ctx: CameraContext) -> int:
    return i - ctx.pre_roll


def _make_learned_g(a: float, b: float):
    """Build a learned-linear g(i) = round(a*i + b)."""
    def _g(i: int, _ctx: CameraContext) -> int:
        return int(round(a * i + b))
    return _g


