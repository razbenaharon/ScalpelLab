"""Validate the composed OLD-MP4 -> SEQ -> NEW-MP4 frame mapping.

The OLD MP4s under ``D:\\Rec_Backup`` were generated by an earlier exporter
(``C:\\Users\\user\\Downloads\\exporters\\old.py``) that did:

    ffmpeg -hwaccel cuda -r 30 -i <seq> -c:v h264_nvenc ... <out.mp4>

No IDX consultation, no ``tpad`` pre-roll, no ``fps=30`` resampling filter,
no group-wide alignment. There is also a CLExport fallback path used on
ffmpeg failure. That makes ``old_mp4_frame_index == seq_frame_index`` a
plausible BUT UNVERIFIED hypothesis.

The NEW MP4s under ``MP4_ROOT`` are produced by
``scripts/3_seq_to_mp4_convert.py`` via an IDX-driven mkvmerge VFR ->
``-vf fps=30`` ffmpeg pipeline with ``tpad start=<pre_roll>`` and a group
target duration. For a SEQ frame ``K`` the NEW MP4 frame index is

    f(K) = pre_roll + round((t_seq[K] - t_seq[0]) * 30)

So the round-trip from an annotation timed against the OLD MP4 to the
corresponding NEW MP4 frame is the composition ``j_new = f(g(i_old))``,
where ``g`` is the unknown OLD-MP4 -> SEQ frame mapping that this script
is trying to identify.

Hypotheses for g(i_old) = K_seq
================================
    g_identity         : K = i_old
    g_fps_scale_30     : K = round(i_old * source_fps / 30)
                         (OLD MP4 nominally 30 fps via ``-r 30``, SEQ runs
                         at source_fps from IDX timestamps)
    g_fps_scale_oldfps : K = round(i_old * source_fps / old_fps)
                         (uses ffprobe's reported OLD fps -- catches the
                         case where the ``-r 30`` flag didn't actually
                         produce a 30.000 fps output)
    g_shift_plus1      : K = i_old + 1
    g_shift_minus1     : K = i_old - 1
                         (off-by-one from ffmpeg's SEQ demuxer consuming
                         SPS/PPS as a synthetic first frame, etc.)
    g_pre_roll         : K = i_old - pre_roll
                         (would only matter if the OLD pipeline trimmed
                         leading frames; included for completeness)
    g_linear           : K = round(a*i_old + b)
                         (fitted per camera from observed best matches;
                         appended at runtime, see _fit_learned_linear)

Algorithm (per camera)
======================
For each anchor frame i_old in the OLD MP4 (evenly spaced, edges trimmed):

  1. Extract OLD anchor frame at t = i_old / old_fps -> dHash -> h_old.
  2. For each hypothesis above compute K_pred and then j_pred = f(K_pred).
  3. Scan K over [i_old - SEARCH_RADIUS_SEQ, i_old + SEARCH_RADIUS_SEQ]
     (default +/- 30 SEQ frames ~ +/- 1s at source_fps). For each K
     compute j = f(K) and Hamming(h_old, dHash(NEW frame j)). The K with
     the smallest Hamming is K_empirical -- the dHash-derived truth that
     each closed-form hypothesis is graded against.
  4. dHash(SEQ frame K) is approximated by dHash(NEW MP4 frame f(K)). This
     means the entire validator stays in MP4 space (one cheap ffmpeg
     burst per anchor) and reuses the same 256-bit dHash as the rest of
     the helpers. Caveat: if f itself is mis-mapping a frame in the NEW
     pipeline, the error is attributed to g rather than f. The
     ``min_hamming_local`` column for g_identity remains a sanity check
     on f's correctness.
  5. Per anchor and per hypothesis, report:
       * K_pred, j_pred
       * Hamming at j_pred, min Hamming within j +/- LOCAL_RADIUS
       * best j-offset within that window
       * residual_K = K_pred - K_empirical

A hypothesis is CONFIRMED for a camera if, across the anchors:
  * min_hamming_local is consistently <= GOOD_THRESHOLD bits (default 16)
  * j_pred is consistently the local Hamming minimum on the NEW MP4 side
    (median best_offset within +/- 1 frame)

The residual_K column is reported as a diagnostic but is NOT used to
gate the verdict, because surgical scenes are near-static and the
empirical-K argmin is noise dominated -- many nearby K values give
indistinguishable dHash on a quasi-still frame.

This is a validation tool, not a remapper. No CSV merge with the main
report; this prints a per-camera table and optionally writes JSON/CSV
dumps for the run.
"""

