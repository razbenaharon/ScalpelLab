def _aggregate_and_answer(summary_rows: list[dict], threshold: int) -> None:
    """Aggregate per-camera summary rows and call the winning g hypothesis."""
    if not summary_rows:
        print("No summary rows to aggregate.")
        return

    hypotheses = sorted({r["hypothesis"] for r in summary_rows})

    # ------- Headline: which hypothesis confirms most often?
    print("=" * 102)
    print("AGGREGATE ACROSS ALL (case, camera) PAIRS")
    print("=" * 102)
    print(f"  {'hypothesis':>22s}  {'n_pairs':>7s}  {'n_CONFIRM':>9s}  {'n_PLAUS':>7s}  "
          f"{'n_FAILS':>7s}  {'mean_minH':>9s}  {'p95_minH':>9s}  {'med_|resK|':>10s}")
    overall: dict[str, dict] = {}
    for f in hypotheses:
        rows = [r for r in summary_rows if r["hypothesis"] == f]
        n_pairs = len(rows)
        if n_pairs == 0:
            continue
        verdicts = [r["verdict"] for r in rows]
        mins = np.array([r["mean_min_hamming"] for r in rows
                         if r.get("mean_min_hamming") is not None],
                        dtype=np.float64)
        maxres = np.array([abs(int(r["max_abs_residual_K"])) for r in rows
                           if r.get("max_abs_residual_K") not in (None, "")],
                          dtype=np.float64)
        overall[f] = {
            "n_pairs": n_pairs,
            "n_CONFIRMED": verdicts.count("CONFIRMED"),
            "n_PLAUSIBLE": verdicts.count("PLAUSIBLE"),
            "n_FAILS":     verdicts.count("FAILS"),
            "mean_minH":   float(np.mean(mins)) if mins.size else float("nan"),
            "p95_minH":    float(np.percentile(mins, 95)) if mins.size else float("nan"),
            "median_maxresK": float(np.median(maxres)) if maxres.size else float("nan"),
        }
        print(f"  {f:>22s}  {n_pairs:>7d}  {overall[f]['n_CONFIRMED']:>9d}  "
              f"{overall[f]['n_PLAUSIBLE']:>7d}  {overall[f]['n_FAILS']:>7d}  "
              f"{overall[f]['mean_minH']:>9.2f}  {overall[f]['p95_minH']:>9.2f}  "
              f"{overall[f]['median_maxresK']:>10.2f}")
    print()

    # ------- Pick the overall winner.
    if overall:
        winner = max(
            overall.items(),
            key=lambda kv: (kv[1]["n_CONFIRMED"], -kv[1]["mean_minH"]),
        )
        print(f"WINNER: {winner[0]}  ({winner[1]['n_CONFIRMED']} CONFIRMED / "
              f"{winner[1]['n_pairs']} pairs, mean_minH={winner[1]['mean_minH']:.2f})")
        print()

    # ------- Per-camera g_linear slope/intercept stability across cases.
    print("Per-camera g_linear slope/intercept across cases:")
    print(f"  {'camera':>22s}  {'n_cases':>7s}  {'a_range':>22s}  {'b_range':>22s}")
    by_camera: dict[str, list[dict]] = {}
    for r in summary_rows:
        # Pick one row per (case, camera) -- g_identity is always present.
        if r["hypothesis"] != "g_identity":
            continue
        by_camera.setdefault(r["camera_name"], []).append(r)
    for cam, rows in sorted(by_camera.items()):
        if not rows:
            continue
        a_learned = [float(r["learned_a"]) for r in rows
                     if r.get("learned_a") not in (None, "")]
        b_learned = [float(r["learned_b"]) for r in rows
                     if r.get("learned_b") not in (None, "")]
        fmt_a = (f"{min(a_learned):.6f}..{max(a_learned):.6f}"
                 if a_learned else "-")
        fmt_b = (f"{min(b_learned):.2f}..{max(b_learned):.2f}"
                 if b_learned else "-")
        print(f"  {cam:>22s}  {len(rows):>7d}  {fmt_a:>22s}  {fmt_b:>22s}")
    print()

    # ------- CLExport-suspect cameras.
    flagged = [(r["recording_date"], r["case_no"], r["camera_name"])
               for r in summary_rows
               if r["hypothesis"] == "g_identity" and str(r.get("clexport_flag")) == "1"]
    if flagged:
        print(f"CLExport-suspect (no closed-form hypothesis fits) -- "
              f"{len(set(flagged))} (case, camera) pairs:")
        for d, c, cam in sorted(set(flagged)):
            print(f"  {d} Case{c} {cam}")
        print()

    # ------- dHash threshold calibration for the winning hypothesis.
    if overall:
        primary = winner[0]
        primary_rows = [r for r in summary_rows if r["hypothesis"] == primary]
        if primary_rows:
            meds = np.array([r["median_min_hamming"] for r in primary_rows
                             if r.get("median_min_hamming") is not None],
                            dtype=np.float64)
            means = np.array([r["mean_min_hamming"] for r in primary_rows
                              if r.get("mean_min_hamming") is not None],
                             dtype=np.float64)
            print(f"dHash distribution under winning hypothesis '{primary}':")
            print(f"  per-(case,camera) median min_hamming:  "
                  f"mean={float(np.mean(meds)):.2f}  median={float(np.median(meds)):.2f}  "
                  f"p90={float(np.percentile(meds, 90)):.2f}  "
                  f"p99={float(np.percentile(meds, 99)):.2f}  "
                  f"max={float(np.max(meds)):.2f}")
            print(f"  per-(case,camera) mean min_hamming:    "
                  f"mean={float(np.mean(means)):.2f}  median={float(np.median(means)):.2f}  "
                  f"p90={float(np.percentile(means, 90)):.2f}  "
                  f"p99={float(np.percentile(means, 99)):.2f}  "
                  f"max={float(np.max(means)):.2f}")
            print(f"  PASS threshold (--hamming-threshold)  = {threshold} / 256")
            n_pairs_failing_thresh = int(np.sum(meds > threshold))
            print(f"  pairs with median(min_hamming) > threshold: "
                  f"{n_pairs_failing_thresh} / {len(meds)}")
    print()


def main(argv: list[str] | None = None) -> int:
    args = _parse_args(argv)

    ffmpeg = _resolve_tool("ffmpeg")
    ffprobe = _resolve_tool("ffprobe")
    if not ffmpeg or not ffprobe:
        print("ffmpeg / ffprobe not found on PATH.", file=sys.stderr)
        return 2

    cameras_filter: set[str] | None = set(args.cameras) if args.cameras else None
    detailed_rows: list[dict] = []
    summary_rows: list[dict] = []
    json_dump: list[dict] = []
    t_start = time.time()

    for rec_date, case_no in args.cases:
        # Group-wise t_global_start for this case (from DB).
        cam_first = _load_camera_first_times(args.db, rec_date, case_no)
        if not cam_first:
            print(f"[skip case] {rec_date} Case{case_no}: no seq_enriched timing rows")
            continue
        group_t_start: dict[str, float] = {}
        for cam, t0 in cam_first.items():
            grp = _camera_group(cam)
            if grp == "UNKNOWN":
                continue
            if t0 < group_t_start.get(grp, float("inf")):
                group_t_start[grp] = t0

        print(f"\n>>>>>> CASE {rec_date} Case{case_no} <<<<<<")
        for camera in sorted(cam_first.keys()):
            if cameras_filter is not None and camera not in cameras_filter:
                continue
            ctx = _build_context_for_camera(args, rec_date, case_no, camera, group_t_start, ffprobe)
            if ctx is None:
                print(f"[skip] {camera}: setup failed (missing MP4/IDX/probe)")
                continue

            # Pass 1: closed-form hypotheses + empirical K search.
            results = validate_camera(
                ctx, ffmpeg, args.samples, args.local_radius, args.search_radius_seq,
            )

            # Fit g_linear from clean empirical K_empirical points; re-run
            # the per-hypothesis evaluator once g_linear is known so it
            # appears in the per-anchor table. We only need the per_formula
            # block for g_linear, so we re-evaluate cheaply: the burst
            # window already covers the relevant span -- but it's simpler
            # to just call _evaluate_one_anchor with the g_linear predictor
            # added.
            learned_ab = _fit_learned_linear(results)
            if learned_ab is not None:
                a, b = learned_ab
                extra = [(LEARNED_NAME, _make_learned_g(a, b))]
                # Rerun only the hypothesis evaluation; we keep K_empirical
                # from pass 1 by stitching the new per_formula[g_linear]
                # block onto each anchor.
                for anc in results:
                    if "error" in anc:
                        continue
                    new_anc = _evaluate_one_anchor(
                        ctx, anc["i_old"], ffmpeg, args.local_radius,
                        args.search_radius_seq, extra,
                    )
                    pf_new = new_anc.get("per_formula") or {}
                    if LEARNED_NAME in pf_new:
                        anc.setdefault("per_formula", {})[LEARNED_NAME] = pf_new[LEARNED_NAME]
                        anc.setdefault("predictions", {})[LEARNED_NAME] = (
                            new_anc.get("predictions") or {}
                        ).get(LEARNED_NAME, {})

            summary = summarise(results)
            emp = empirical_health(results)

            # CLExport flag: every closed-form g hypothesis is FAILS (not
            # even PLAUSIBLE) AND the empirical search still found a
            # clean match. That means the OLD MP4 has frames somewhere
            # in the search radius (so mapping is recoverable) but not
            # at any closed-form K.
            closed_form_names = [n for n, _ in G_HYPOTHESES]
            any_at_least_plausible = any(
                _verdict(summary.get(n, {}), args.samples) in ("CONFIRMED", "PLAUSIBLE")
                for n in closed_form_names
            )
            clexport_flag = (
                (not any_at_least_plausible)
                and emp.get("n", 0) > 0
                and emp.get("median", 1e9) <= _CLEXPORT_FLAG_THRESHOLD_BITS
            )

            print_camera_report(ctx, results, summary, emp, learned_ab, clexport_flag)

            # ----- Per-anchor detailed rows -----
            for anc in results:
                if "per_formula" not in anc:
                    continue
                i_old = anc["i_old"]
                K_emp = anc.get("K_empirical")
                j_emp = anc.get("j_empirical")
                h_emp = anc.get("hamming_empirical")
                for fname, info in anc["per_formula"].items():
                    K_pred = info.get("K_pred")
                    pred_j = info.get("predicted_j")
                    min_h = info.get("min_hamming_local")
                    ham_at = info.get("hamming_at_predicted")
                    best_off = info.get("best_offset")
                    resid_K = info.get("residual_K")
                    is_oor = info.get("out_of_range", False)
                    if is_oor or min_h is None:
                        pf = "OOR"
                    elif (min_h <= args.hamming_threshold
                          and resid_K is not None
                          and abs(resid_K) <= _RESIDUAL_K_TOLERANCE):
                        pf = "PASS"
                    elif min_h <= args.hamming_threshold:
                        pf = "WRONG_K"
                    else:
                        pf = "VERIFY_FAILED"
                    detailed_rows.append({
                        "recording_date": rec_date,
                        "case_no": case_no,
                        "camera_name": camera,
                        "group_name": ctx.group_name,
                        "i_old": i_old,
                        "K_empirical": K_emp if K_emp is not None else "",
                        "j_empirical": j_emp if j_emp is not None else "",
                        "hamming_empirical": h_emp if h_emp is not None else "",
                        "hypothesis": fname,
                        "K_pred": K_pred if K_pred is not None else "",
                        "predicted_j": pred_j if pred_j is not None else "",
                        "hamming_at_predicted": ham_at if ham_at is not None else "",
                        "min_hamming_local": min_h if min_h is not None else "",
                        "best_offset": best_off if best_off is not None else "",
                        "residual_K": resid_K if resid_K is not None else "",
                        "pass_fail": pf,
                        "out_of_range": "1" if is_oor else "0",
                    })

            # ----- Per-camera summary rows -----
            n_anch = sum(1 for r in results if "per_formula" in r)
            for fname, s in summary.items():
                if not s or s.get("n", 0) == 0:
                    continue
                summary_rows.append({
                    "recording_date": rec_date,
                    "case_no": case_no,
                    "camera_name": camera,
                    "group_name": ctx.group_name,
                    "source_fps": f"{ctx.source_fps:.6f}",
                    "pre_roll": ctx.pre_roll,
                    "idx_frames": ctx.idx_frames,
                    "old_nb_frames": ctx.old_nb_frames,
                    "new_nb_frames": ctx.new_nb_frames,
                    "old_fps": f"{ctx.old_fps:.6f}",
                    "learned_a": f"{learned_ab[0]:.8f}" if learned_ab else "",
                    "learned_b": f"{learned_ab[1]:.3f}" if learned_ab else "",
                    "empirical_mean_H": f"{emp['mean']:.4f}" if emp.get("n") else "",
                    "empirical_median_H": f"{emp['median']:.4f}" if emp.get("n") else "",
                    "empirical_max_H": f"{emp['max']:.4f}" if emp.get("n") else "",
                    "clexport_flag": "1" if clexport_flag else "0",
                    "hypothesis": fname,
                    "n": s["n"],
                    "n_good": s["n_good"],
                    "n_centred": s["n_centred"],
                    "n_resid_ok": s["n_resid_ok"],
                    "mean_min_hamming":     f"{s['mean_min_hamming']:.4f}",
                    "median_min_hamming":   f"{s['median_min_hamming']:.4f}",
                    "mean_ham_at_predicted": f"{s['mean_ham_at_predicted']:.4f}",
                    "median_best_offset":   s["median_best_offset"],
                    "max_abs_best_offset":  s["max_abs_best_offset"],
                    "median_residual_K":    s["median_residual_K"],
                    "max_abs_residual_K":   s["max_abs_residual_K"],
                    "verdict":              _verdict(s, n_anch),
                })

            json_dump.append({
                "recording_date": rec_date,
                "case_no": case_no,
                "camera": camera,
                "group": ctx.group_name,
                "pre_roll": ctx.pre_roll,
                "source_fps": ctx.source_fps,
                "idx_frames": ctx.idx_frames,
                "old_nb_frames": ctx.old_nb_frames,
                "new_nb_frames": ctx.new_nb_frames,
                "old_fps": ctx.old_fps,
                "new_fps": ctx.new_fps,
                "learned_ab": list(learned_ab) if learned_ab else None,
                "empirical_health": emp,
                "clexport_flag": clexport_flag,
                "anchors": results,
                "summary": summary,
            })

    # ----- Build numeric fields back into summary_rows for analysis -----
    for r in summary_rows:
        try:
            r["mean_min_hamming"] = float(r["mean_min_hamming"])
            r["median_min_hamming"] = float(r["median_min_hamming"])
        except (TypeError, ValueError):
            pass

    if args.out_detailed_csv:
        _write_detailed_csv(detailed_rows, Path(args.out_detailed_csv).resolve())
        print(f"Wrote detailed CSV ({len(detailed_rows)} rows) "
              f"to {Path(args.out_detailed_csv).resolve()}")
    if args.out_summary_csv:
        _write_summary_csv(summary_rows, Path(args.out_summary_csv).resolve())
        print(f"Wrote summary CSV ({len(summary_rows)} rows) "
              f"to {Path(args.out_summary_csv).resolve()}")
    if args.out_json:
        op = Path(args.out_json).resolve()
        op.parent.mkdir(parents=True, exist_ok=True)
        with op.open("w", encoding="utf-8") as fh:
            json.dump({
                "cases": [list(p) for p in args.cases],
                "samples": args.samples,
                "local_radius": args.local_radius,
                "search_radius_seq": args.search_radius_seq,
                "hamming_threshold": args.hamming_threshold,
                "per_camera": json_dump,
            }, fh, indent=2)
        print(f"Wrote JSON dump to {op}")

    _aggregate_and_answer(summary_rows, args.hamming_threshold)
    print(f"Done in {time.time() - t_start:.1f}s.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
