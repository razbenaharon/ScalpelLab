def _resolve_tool(name: str) -> str | None:
    p = shutil.which(name)
    if p:
        return p
    for c in (rf"C:\Program Files\ffmpeg\bin\{name}.exe",
              rf"C:\ffmpeg\bin\{name}.exe",
              rf"C:\Program Files (x86)\ffmpeg\bin\{name}.exe"):
        if Path(c).exists():
            return c
    return None


def _extract_window(mp4: Path, t_seek: float, n_frames: int, ffmpeg: str) -> np.ndarray | None:
    """Extract ``n_frames`` consecutive grayscale 17x16 frames starting near ``t_seek``.

    Two-pass seek (fast keyframe + precise) for frame-accurate output.
    """
    if n_frames <= 0:
        return None
    lead = 2.0
    pre = max(0.0, t_seek - lead)
    cmd = [
        ffmpeg, "-hide_banner", "-loglevel", "error",
        "-ss", f"{pre:.4f}",
        "-i", str(mp4),
        "-ss", f"{t_seek - pre:.4f}",
        "-an",
        "-frames:v", str(n_frames),
        "-vf", f"scale={_DHASH_W}:{_DHASH_H},format=gray",
        "-f", "rawvideo", "-pix_fmt", "gray", "pipe:1",
    ]
    try:
        proc = subprocess.run(cmd, capture_output=True, timeout=60)
    except (subprocess.TimeoutExpired, OSError):
        return None
    if proc.returncode != 0:
        return None
    n_got = len(proc.stdout) // _DHASH_BYTES
    if n_got == 0:
        return None
    return np.frombuffer(proc.stdout[: n_got * _DHASH_BYTES], dtype=np.uint8).reshape(
        n_got, _DHASH_H, _DHASH_W
    )


def _dhash_batch(frames: np.ndarray) -> list[int]:
    diff = (frames[:, :, 1:] > frames[:, :, :-1]).reshape(frames.shape[0], -1)
    packed = np.packbits(diff.astype(np.uint8), axis=1)
    return [int.from_bytes(row.tobytes(), "big") for row in packed]


def _hamming(a: int, b: int) -> int:
    return (int(a) ^ int(b)).bit_count()


