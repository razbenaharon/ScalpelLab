# Per-camera validation
# ---------------------------------------------------------------------------
def _pick_anchors(ctx: CameraContext, n_anchors: int) -> list[int]:
    """Evenly-spaced anchors in OLD frame space, avoiding the first/last 5%."""
    n_old = ctx.old_nb_frames
    if n_old <= 0:
        return []
    lo = int(n_old * 0.05)
    hi = int(n_old * 0.95)
    if hi <= lo:
        return []
    if n_anchors == 1:
        return [(lo + hi) // 2]
    step = (hi - lo) / (n_anchors - 1)
    out = []
    for k in range(n_anchors):
        i = int(round(lo + k * step))
        # Stay within OLD MP4's valid index range.
        i = max(0, min(i, ctx.old_nb_frames - 1))
        out.append(i)
    return out


def _fit_learned_linear(anchor_results: list[dict]) -> tuple[float, float] | None:
    """Fit `K = a*i + b` from anchors with a clean empirical K_empirical.

    Returns None if there are fewer than 3 usable points.
    """
    pts: list[tuple[int, int]] = []
    for anc in anchor_results:
        K_emp = anc.get("K_empirical")
        h_emp = anc.get("hamming_empirical")
        if K_emp is None or h_emp is None:
            continue
        if h_emp > _GOOD_THRESHOLD_BITS * 2:
            continue
        pts.append((int(anc["i_old"]), int(K_emp)))
    if len(pts) < 3:
        return None
    xs = np.array([p[0] for p in pts], dtype=np.float64)
    ys = np.array([p[1] for p in pts], dtype=np.float64)
    a, b = np.polyfit(xs, ys, 1)
    return float(a), float(b)


def _evaluate_one_anchor(
    ctx: CameraContext,
    i_old: int,
    ffmpeg: str,
    local_radius: int,
    search_radius_seq: int,
    hypotheses: list[tuple[str, callable]],  # type: ignore[type-arg]
) -> dict:
    """Run the full composed validation for a single OLD anchor frame.

    Returns a dict with keys: i_old, h_old (optional), K_empirical,
    j_empirical, hamming_empirical, predictions (per hypothesis), and
    per_formula (per hypothesis metric block). On failure, returns a
    dict containing 'error' and as much partial data as is available.
    """
    t_old = i_old / ctx.old_fps if ctx.old_fps else i_old / TARGET_FPS

    # 1. Extract the OLD anchor frame -> h_old.
    old_frames = _extract_window(ctx.old_path, t_old, 1, ffmpeg)
    if old_frames is None or old_frames.shape[0] == 0:
        return {"i_old": i_old, "error": "OLD_EXTRACT_FAILED"}
    h_old = _dhash_batch(old_frames)[0]

    # 2. Closed-form hypothesis predictions: K_pred, j_pred = f(K_pred).
    predictions: dict[str, dict] = {}
    for name, gfn in hypotheses:
        try:
            K_pred = int(gfn(i_old, ctx))
        except (IndexError, ValueError, OverflowError):
            predictions[name] = {"K_pred": None, "j_pred": -1}
            continue
        if 0 <= K_pred < ctx.idx_frames:
            j_pred = _f_seq_to_new(K_pred, ctx)
        else:
            j_pred = -1
        predictions[name] = {"K_pred": K_pred, "j_pred": j_pred}

    # 3. Search K over [i_old - sR, i_old + sR] (clipped to IDX range).
    K_lo = max(0, i_old - search_radius_seq)
    K_hi = min(ctx.idx_frames - 1, i_old + search_radius_seq)
    if K_hi < K_lo:
        return {
            "i_old": i_old, "error": "EMPTY_SEARCH_RANGE",
            "predictions": predictions,
        }
    search_K = list(range(K_lo, K_hi + 1))
    search_j = [_f_seq_to_new(K, ctx) for K in search_K]

    # 4. Union of all j values (search + hypothesis predictions +/- local_radius).
    candidates: set[int] = set()
    for j in search_j:
        if 0 <= j < ctx.new_nb_frames:
            candidates.add(j)
    for info in predictions.values():
        j = info["j_pred"]
        if j is None or j < 0:
            continue
        lo = max(0, j - local_radius)
        hi = min(ctx.new_nb_frames - 1, j + local_radius)
        candidates.update(range(lo, hi + 1))
    if not candidates:
        return {
            "i_old": i_old, "error": "ALL_PREDICTIONS_OUT_OF_RANGE",
            "predictions": predictions,
        }

    # 5. One ffmpeg burst over the contiguous span [c_min..c_max].
    c_min, c_max = min(candidates), max(candidates)
    n_to_extract = c_max - c_min + 1
    t_seek_new = c_min / TARGET_FPS
    new_frames = _extract_window(ctx.new_path, t_seek_new, n_to_extract, ffmpeg)
    if new_frames is None or new_frames.shape[0] == 0:
        return {
            "i_old": i_old, "error": "NEW_EXTRACT_FAILED",
            "predictions": predictions,
        }
    new_hashes = _dhash_batch(new_frames)
    j_to_hash: dict[int, int] = {
        c_min + k: new_hashes[k] for k in range(min(n_to_extract, len(new_hashes)))
    }

    # 6. Empirical K: the K in the search range that minimizes Hamming.
    # Tie-break by smallest |K - i_old| (prefer the K closest to identity).
    best_tuple: tuple[int, int, int, int] | None = None  # (hamming, |dK|, K, j)
    for K, j in zip(search_K, search_j):
        if j not in j_to_hash:
            continue
        h = _hamming(h_old, j_to_hash[j])
        tup = (h, abs(K - i_old), K, j)
        if best_tuple is None or tup < best_tuple:
            best_tuple = tup
    if best_tuple is None:
        return {
            "i_old": i_old, "error": "NO_SEARCH_HITS",
            "predictions": predictions,
        }
    hamming_empirical, _, K_empirical, j_empirical = best_tuple

    # 7. Per-hypothesis metric block.
    per_formula: dict[str, dict] = {}
    for name, info in predictions.items():
        K_pred = info["K_pred"]
        j_pred = info["j_pred"]
        if j_pred is None or j_pred < 0 or j_pred not in j_to_hash:
            per_formula[name] = {
                "K_pred": K_pred,
                "predicted_j": j_pred if j_pred is not None else -1,
                "hamming_at_predicted": None,
                "min_hamming_local": None,
                "best_offset": None,
                "residual_K": (K_pred - K_empirical) if K_pred is not None else None,
                "out_of_range": True,
            }
            continue
        ham_at = _hamming(h_old, j_to_hash[j_pred])
        best_ham = ham_at
        best_off = 0
        for d in range(-local_radius, local_radius + 1):
            k = j_pred + d
            if k not in j_to_hash:
                continue
            h = _hamming(h_old, j_to_hash[k])
            if h < best_ham:
                best_ham = h
                best_off = d
        per_formula[name] = {
            "K_pred": K_pred,
            "predicted_j": j_pred,
            "hamming_at_predicted": ham_at,
            "min_hamming_local": best_ham,
            "best_offset": best_off,
            "residual_K": (K_pred - K_empirical) if K_pred is not None else None,
            "out_of_range": False,
        }

    return {
        "i_old": i_old,
        "K_empirical": K_empirical,
        "j_empirical": j_empirical,
        "hamming_empirical": hamming_empirical,
        "predictions": predictions,
        "per_formula": per_formula,
    }


def validate_camera(
    ctx: CameraContext, ffmpeg: str, n_anchors: int, local_radius: int,
    search_radius_seq: int,
    extra_predictors: list[tuple[str, callable]] | None = None,  # type: ignore[type-arg]
) -> list[dict]:
    """For each anchor, evaluate every hypothesis under the composed mapping.

    ``extra_predictors`` is appended after the global G_HYPOTHESES list --
    used to inject ``g_linear`` after a per-camera (a, b) fit.
    """
    hypotheses = G_HYPOTHESES + (extra_predictors or [])
    anchors = _pick_anchors(ctx, n_anchors)
    if not anchors:
        return []

    anchor_results: list[dict] = []
    for i_old in anchors:
        anchor_results.append(_evaluate_one_anchor(
            ctx, i_old, ffmpeg, local_radius, search_radius_seq, hypotheses
        ))
    return anchor_results


